const assert=require('node:assert/strict');
const D=require('./calc.js');
assert.equal(D.parse('2000-03-01')-D.parse('2000-02-28'),2);
assert.equal(D.parse('1900-03-01')-D.parse('1900-02-28'),1);
assert.equal(D.iso(D.milestone(D.parse('2000-01-01'),100)),'2000-04-10');
assert.equal(D.iso(D.milestone(D.parse('2000-01-01'),100,true)),'2000-04-09');
assert.equal(D.iso(D.milestone(D.parse('2000-01-01'),1000)),'2002-09-27');
assert.equal(D.iso(D.milestone(D.parse('2024-02-29'),1,true)),'2024-02-29');
assert.equal(D.iso(D.anniversary(D.parse('2024-02-29'),2025)),'2025-02-28');
assert.deepEqual(D.age(D.parse('2000-02-29'),D.parse('2025-02-28')),{years:25,months:0,days:0,totalMonths:300});
assert.deepEqual(D.age(D.parse('2024-01-31'),D.parse('2024-03-30')),{years:0,months:1,days:30,totalMonths:1});
assert.deepEqual(D.age(D.parse('2024-01-31'),D.parse('2024-02-29')),{years:0,months:1,days:0,totalMonths:1});
assert.equal(D.parse('2024-03-11')-D.parse('2024-03-09'),2);
assert.equal(D.iso(D.parse('0001-01-01')),'0001-01-01');
assert.equal(D.iso(D.parse('0099-12-31')),'0099-12-31');
for(const bad of ['2023-02-29','1900-02-29','2024-04-31','0000-01-01','2024-13-01','garbage'])assert.throws(()=>D.parse(bad));
for(const bad of [0,-1,1.5,1000001,NaN])assert.throws(()=>D.milestone(D.parse('2000-01-01'),bad));
assert.throws(()=>D.milestone(D.parse('9999-12-31'),1));
console.log('All date calculation checks passed.');
